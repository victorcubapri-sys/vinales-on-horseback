function readPreference(key) {
  try {
    return window.localStorage.getItem(key);
  } catch {
    return null;
  }
}

function savePreference(key, value) {
  try {
    window.localStorage.setItem(key, value);
  } catch {
    // The page remains usable when browser storage is unavailable.
  }
}

function setLanguage(language) {
  const dict = translations[language] || translations.es;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dict[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll("[data-es][data-en]").forEach((element) => {
    element.innerHTML = element.dataset[language];
  });
  const toggle = document.querySelector(".language-toggle");
  toggle.textContent = language === "es" ? "EN" : "ES";
  toggle.setAttribute("aria-label", language === "es" ? "Switch language to English" : "Cambiar idioma a español");
  toggle.lang = language === "es" ? "en" : "es";
  savePreference("vinales-language", language);
  BUSINESS.locale = language;
}

