function setupNavigation() {
  const toggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector("#primary-nav");
  if (!toggle || !nav) return;
  const closeMenu = () => {
    toggle.setAttribute("aria-expanded", "false");
    nav.classList.remove("is-open");
    toggle.setAttribute("aria-label", BUSINESS.locale === "es" ? "Abrir menú" : "Open menu");
  };
  toggle.addEventListener("click", () => {
    const isOpen = toggle.getAttribute("aria-expanded") !== "true";
    toggle.setAttribute("aria-expanded", String(isOpen));
    nav.classList.toggle("is-open", isOpen);
    toggle.setAttribute("aria-label", isOpen
      ? (BUSINESS.locale === "es" ? "Cerrar menú" : "Close menu")
      : (BUSINESS.locale === "es" ? "Abrir menú" : "Open menu"));
  });
  nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

function setupTheme() {
  const toggle = document.querySelector(".theme-toggle");
  if (!toggle) return;
  const preferred = readPreference("vinales-theme");
  if (preferred === "dark") document.documentElement.dataset.theme = "dark";
  toggle.addEventListener("click", () => {
    const dark = document.documentElement.dataset.theme !== "dark";
    document.documentElement.dataset.theme = dark ? "dark" : "light";
    if (!dark) delete document.documentElement.dataset.theme;
    savePreference("vinales-theme", dark ? "dark" : "light");
    toggle.setAttribute("aria-label", dark ? "Activar modo claro" : "Activar modo oscuro");
  });
}

function setupMotion() {
  const elements = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    elements.forEach((element) => element.classList.add("is-visible"));
    return;
  }
  const observer = new IntersectionObserver((entries, instance) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        instance.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  elements.forEach((element) => observer.observe(element));
}

function setupLightbox() {
  const dialog = document.querySelector("#lightbox");
  if (!dialog) return;
  const image = dialog.querySelector("img");
  document.querySelectorAll("[data-lightbox]").forEach((button) => {
    button.addEventListener("click", () => {
      image.src = button.dataset.lightbox;
      image.alt = button.dataset.alt || "";
      dialog.showModal();
      document.body.classList.add("no-scroll");
      dialog.querySelector(".lightbox-close").focus();
    });
  });
  const close = () => {
    dialog.close();
    image.removeAttribute("src");
    document.body.classList.remove("no-scroll");
  };
  dialog.querySelector(".lightbox-close").addEventListener("click", close);
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) close();
  });
  dialog.addEventListener("close", () => document.body.classList.remove("no-scroll"));
}

function setupContactForm() {
  const form = document.querySelector("#contact-form");
  if (!form) return;
  const status = document.querySelector("#form-status");
  const today = new Date();
  const localToday = new Date(today.getTime() - today.getTimezoneOffset() * 60000).toISOString().slice(0, 10);
  document.querySelector("#date").min = localToday;

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const data = new FormData(form);
    const errors = {
      name: data.get("name").trim().length < 2 || data.get("name").trim().length > 80,
      date: Boolean(data.get("date") && data.get("date") < localToday),
      message: data.get("message").trim().length < 10 || data.get("message").trim().length > 1000,
      consent: !document.querySelector("#consent").checked
    };
    const dict = translations[BUSINESS.locale];
    Object.entries(errors).forEach(([field, invalid]) => {
      const control = document.querySelector(`#${field}`);
      const error = document.querySelector(`#${field}-error`);
      if (control) control.setAttribute("aria-invalid", String(invalid));
      if (error) error.textContent = invalid ? dict[`error${field[0].toUpperCase()}${field.slice(1)}`] : "";
    });
    status.classList.remove("error");

    if (data.get("website")) {
      status.textContent = dict.spam;
      status.classList.add("error");
      return;
    }
    if (Object.values(errors).some(Boolean)) {
      status.textContent = dict.errorForm;
      status.classList.add("error");
      form.querySelector('[aria-invalid="true"], input:invalid, textarea:invalid')?.focus();
      return;
    }

    const body = [
      `${BUSINESS.locale === "es" ? "Nombre" : "Name"}: ${data.get("name").trim()}`,
      `${BUSINESS.locale === "es" ? "Fecha preferida" : "Preferred date"}: ${data.get("date") || (BUSINESS.locale === "es" ? "Flexible" : "Flexible")}`,
      "",
      data.get("message").trim()
    ].join("\n");
    status.textContent = dict.whatsappOpen;
    window.location.href = `https://wa.me/${BUSINESS.whatsapp}?text=${encodeURIComponent(body)}`;
  });

  form.querySelectorAll("input, textarea").forEach((control) => {
    control.addEventListener("input", () => {
      control.removeAttribute("aria-invalid");
      const error = document.querySelector(`#${control.id}-error`);
      if (error) error.textContent = "";
    });
    control.addEventListener("change", () => {
      control.removeAttribute("aria-invalid");
      const error = document.querySelector(`#${control.id}-error`);
      if (error) error.textContent = "";
    });
  });
}

function setupPrivacyNotice() {
  const banner = document.querySelector("#cookie-banner");
  if (!banner) return;
  if (!readPreference("vinales-privacy-notice")) banner.hidden = false;
  const dismiss = () => {
    banner.hidden = true;
    savePreference("vinales-privacy-notice", "seen");
  };
  banner.querySelector(".cookie-accept").addEventListener("click", dismiss);
  const settings = document.querySelector(".cookie-settings");
  if (settings) {
    settings.addEventListener("click", () => {
      banner.hidden = false;
      banner.querySelector(".cookie-accept").focus();
    });
  }
}

